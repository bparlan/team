#!/usr/bin/env python3
"""Run every task in order, with rich HTML reports.

In-process (eval kernel): spawns members automatically via `agent()`.
From bash: prints `theteam run --only <id>` for each task.

Each task produces a rich HTML report in `reports/` with:
  - Summary statistics
  - Phase-by-phase breakdown
  - Major decisions (for LLM phases)
  - Exit codes and findings
  - Color-coded verdicts

Usage:
    python3 scripts/run_all_tasks.py [--project-root .]
"""
import json
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
TASKS_DIR = ROOT / "tasks"
REPORTS_DIR = ROOT / "reports"
HTML_TEMPLATE = ROOT / "scripts" / "html_template.html"


def _get_agent():
    """Resolve `agent` from the eval kernel's injected builtin."""
    frame = sys._getframe(1)
    while frame is not None:
        if "agent" in frame.f_globals and callable(frame.f_globals["agent"]):
            return frame.f_globals["agent"]
        frame = frame.f_back
    return None


def load_tasks():
    tasks = []
    for path in sorted(TASKS_DIR.glob("task-*.yaml")):
        task = yaml.safe_load(path.read_text(encoding="utf-8"))
        if isinstance(task, dict):
            tasks.append(task)
    tasks.sort(key=lambda t: t.get("order", 99))
    return tasks


def run_script_phase(phase):
    """Run a script phase. Exit codes: 0=pass, 3=findings, 2=cannot evaluate."""
    script = ROOT / phase["script"]
    if not script.exists():
        return False, "script not found: " + phase["script"]
    try:
        r = subprocess.run(
            ["python3", str(script)] + [str(a) for a in phase.get("args", [])],
            capture_output=True, text=True,
            timeout=phase.get("timeout_seconds", 300),
            cwd=str(ROOT),
        )
        if r.returncode == 2:
            return False, "cannot evaluate: " + (r.stdout + r.stderr).strip()[:200]
        return True, (r.stdout + r.stderr).strip()[:200]
    except subprocess.TimeoutExpired:
        return False, "timeout: " + phase["name"]
    except Exception as e:
        return False, "error: " + str(e)


def run_llm_phase(phase, project_root):
    """Spawn a member for an LLM phase."""
    agent_fn = _get_agent()
    if agent_fn is None:
        return False, "no agent available (run from eval kernel, not bash)"

    prompt_path = ROOT / phase["prompt_file"]
    if not isinstance(project_root, Path):
        project_root = Path(project_root)
    output_path = project_root / phase["output"]
    output_path.parent.mkdir(parents=True, exist_ok=True)

    if not prompt_path.exists():
        return False, "prompt not found: " + phase["prompt_file"]

    prompt = prompt_path.read_text(encoding="utf-8")
    agent_type = phase.get("agent_type", "task")

    try:
        result = agent_fn(prompt, agent=agent_type, handle=True)
        text = result.get("text", str(result)) if isinstance(result, dict) else str(result)
        output_path.write_text(text, encoding="utf-8")
        return True, "wrote " + phase["output"]
    except Exception as e:
        return False, "spawn failed: " + str(e)


def run_task(task, project_root):
    """Run one task's phases in order."""
    results = []
    for phase in task.get("phases", []):
        runner = phase.get("runner")
        name = phase.get("name", "?")

        if runner == "llm":
            ok, detail = run_llm_phase(phase, project_root)
        elif phase.get("script"):
            ok, detail = run_script_phase(phase)
        else:
            ok, detail = False, "no script and no runner"

        results.append({"ok": ok, "detail": detail, "phase": phase})
    return results


def render_html_report(task, phase_results, project_name):
    """Render a rich HTML report for a single task using the reporter skill."""
    title = f"Task: {task['name']}"
    subtitle = f"ID: {task['id']} | Phases: {len(task['phases'])}"

    stats = {"ok": 0, "warn": 0, "bad": 0, "info": 0}
    findings = []
    details = []

    for phase in task['phases']:
        status, output = phase_results.get(phase['name'], (False, "No output"))
        level = "ok" if status else "bad"
        stats[level] += 1
        findings.append({
            "title": f"Phase: {phase['name']}",
            "level": level,
            "why": output or "No specific output provided."
        })
        details.append({
            "summary": f"Phase {phase['name']} Output",
            "content": output or "No detailed output."
        })

    report_data = {
        "title": title,
        "subtitle": subtitle,
        "stats": stats,
        "decisions": [],  # Major decisions will be added in consolidated report
        "findings": findings,
        "details": details,
        "meta": f"Generated by run_all_tasks.py for {project_name}"
    }

    # Write the JSON data to a temporary file
    json_path = REPORTS_DIR / f"{task['id']}.json"
    json_path.write_text(json.dumps(report_data, indent=2, ensure_ascii=False), encoding="utf-8")

    # Invoke the reporter skill to generate the HTML
    output_html_path = REPORTS_DIR / f"{task['id']}.html"
    try:
        subprocess.run(
            ["reporter", str(json_path), "--title", title, "--output", str(output_html_path)],
            check=True,
            capture_output=True,
            text=True
        )
        print(f"[INFO] Generated HTML report for {task['id']} at {output_html_path}", file=sys.stderr)
    except subprocess.CalledProcessError as e:
        print(f"[ERROR] Failed to generate HTML for {task['id']}: {e.stderr}", file=sys.stderr)
        return "" # Return empty string on error

    return output_html_path.read_text(encoding="utf-8")
def render_consolidated_report(task_results, project_name):
    """Render a consolidated HTML report for all tasks using the reporter skill."""
    title = f"Run All Tasks Summary - {project_name}"
    subtitle = f"Total tasks: {len(task_results)}"

    stats = {"ok": 0, "warn": 0, "bad": 0, "info": 0}
    findings = []
    details = []

    for task_id, task_name, passed, html_path in task_results:
        level = "ok" if passed else "bad"
        stats[level] += 1
        findings.append({
            "title": f"Task: {task_name}",
            "level": level,
            "why": f"Task {'passed' if passed else 'failed'}. Report: {html_path}"
        })
        details.append({
            "summary": f"Task {task_name} Report",
            "content": f"HTML report available at: {html_path}"
        })

    report_data = {
        "title": title,
        "subtitle": subtitle,
        "stats": stats,
        "decisions": [],  # Major decisions can be added by specific tasks
        "findings": findings,
        "details": details,
        "meta": f"Generated by run_all_tasks.py for {project_name}"
    }

    # Write the JSON data to a temporary file
    json_path = REPORTS_DIR / "run-all-summary.json"
    json_path.write_text(json.dumps(report_data, indent=2, ensure_ascii=False), encoding="utf-8")

    # Invoke the reporter skill to generate the HTML
    output_html_path = REPORTS_DIR / "run-all-summary.html"
    try:
        subprocess.run(
            ["reporter", str(json_path), "--title", title, "--output", str(output_html_path)],
            check=True,
            capture_output=True,
            text=True
        )
        print(f"[INFO] Generated consolidated HTML report at {output_html_path}", file=sys.stderr)
    except subprocess.CalledProcessError as e:
        print(f"[ERROR] Failed to generate consolidated HTML: {e.stderr}", file=sys.stderr)
        return ""

    return output_html_path.read_text(encoding="utf-8")

def main():
    project_root = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
    tasks = load_tasks()

    agent_fn = _get_agent()
    if agent_fn is None:
        for t in tasks:
            print("theteam run --only " + t["id"])
        print("")
        print(str(len(tasks)) + " tasks. Run them in order.", file=sys.stderr)
        return 0

    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    all_passed = True
    report_files = []
    task_results = []

    for i, task in enumerate(tasks):
        phase_results = run_task(task, project_root)
        task_passed = all(r["ok"] for r in phase_results)
        all_passed = all_passed and task_passed

        # Render rich HTML report for this task
        html = render_html_report(task, phase_results, project_root.name)
        html_path = REPORTS_DIR / (task["id"] + ".html")
        html_path.write_text(html, encoding="utf-8")
        report_files.append(str(html_path))
        task_results.append((task["id"], task["name"], task_passed, str(html_path)))

        status = "PASS" if task_passed else "FAIL"
        print(f"[{status}] {task['id']}: wrote {html_path}", file=sys.stderr)

    # Render consolidated HTML report for all tasks
    consolidated_html = render_consolidated_report(task_results, project_root.name)
    consolidated_path = REPORTS_DIR / "run-all-summary.html"
    consolidated_path.write_text(consolidated_html, encoding="utf-8")
    print(f"[INFO] wrote {consolidated_path}", file=sys.stderr)

    # Also write aggregate JSON for the orchestrator
    aggregate = {
        "total": len(tasks),
        "passed": sum(1 for r in task_results if r[2]),
        "failed": sum(1 for r in task_results if not r[2]),
        "report_files": report_files
    }
    (REPORTS_DIR / "run-all.json").write_text(
        json.dumps(aggregate, indent=2, ensure_ascii=False), encoding="utf-8"
    )

    print("")
    print(f"{len(tasks)}/{len(tasks)} tasks ok", file=sys.stderr)
    sys.exit(0 if all_passed else 1)