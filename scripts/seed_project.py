#!/usr/bin/env python3
"""
seed_project.py — One-time seed for project convention infrastructure.

Usage:
    python scripts/seed_project.py --project-root <path> [--dry-run]

Writes a seed.yaml into the target project, scaffolds the minimal convention
files and directories, and verifies the result.

The shape is portable and self-contained: no project paths are recorded, no
project content is shipped, and the seed works on any project regardless of
what it contains.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

# ---------------------------------------------------------------------------
# Directory shape — derived from the three construction projects, recorded as
# a SHAPE rather than as their content.  Nothing here names a real project.
#
#   docs/      3/3  documentation hub (skeletons/ sub-convention)
#   scripts/   3/3  tooling
#   src/       3/3  application code
#   tests/     3/3  test suite
#   data/      2/3  structured data
#   .omp/      3/3  theteam home
#
# The four 3/3 directories are required; the rest are optional and created
# only when a project genuinely needs them.
# ---------------------------------------------------------------------------
REQUIRED_DIRS = ["docs", "scripts", "src", "tests"]
OPTIONAL_DIRS = ["data"]

# Convention files at the project root.
REQUIRED_FILES = ["AGENTS.md", "README.md"]

SEED_CONTENT = {
    "schema_version": "1.0",
    "directory_shape": {
        "required": REQUIRED_DIRS,
        "optional": OPTIONAL_DIRS,
        "convention": (
            "Required directories exist in every project. Optional ones are "
            "created only when the project needs them. The shape is portable: "
            "no project-specific paths are recorded."
        ),
        "capabilities": {
            "docs/skeletons/": (
                "Not created by the seed. Generated by the `code-search` skill "
                "(run from the project root: `code-search --skeletons`). It is a "
                "capability, not a directory — seeding an empty skeletons/ would "
                "create a directory for a skill that may not be present, which is "
                "the defect the evolution floor exists to prevent."
            ),
        },
    },
    "rule_template": {
        "name": "Core convention requirement",
        "contract": [
            "Every project must have AGENTS.md defining conventions.",
            "Every project must have README.md for documentation.",
            "Every project must have docs/, scripts/, src/ and tests/.",
        ],
        "evidence": "verified",
        "rule_correct": "kept",
        "falsification_test": {
            "command": (
                "test -f AGENTS.md && test -f README.md && "
                "test -d docs && test -d scripts && test -d src && test -d tests"
            ),
            "expected": "All required files and directories exist",
        },
    },
    "evolution_floor": {
        "can_add_rules": True,
        "can_modify": True,
        "can_delete": False,
        "requires_human_approval": True,
    },
}


def write_seed(project_root: Path, seed: dict, dry_run: bool = False) -> Path:
    """Write seed.yaml into the project root.  Returns the file path."""
    import yaml

    target = project_root / "seed.yaml"
    if dry_run:
        print(f"[dry-run] would write {target}")
        return target

    target.write_text(
        yaml.safe_dump(seed, sort_keys=False, allow_unicode=True, width=80)
    )
    return target


def scaffold_directories(project_root: Path, dry_run: bool = False) -> list[str]:
    """Create required and optional directories.  Returns the list created."""
    created: list[str] = []
    for d in REQUIRED_DIRS + OPTIONAL_DIRS:
        path = project_root / d
        if not path.exists():
            if dry_run:
                print(f"[dry-run] would create {path}")
            else:
                path.mkdir(parents=True, exist_ok=True)
                print(f"✓ Created {path}")
            created.append(d)
    return created


def scaffold_files(project_root: Path, dry_run: bool = False) -> None:
    """Create the minimal AGENTS.md and README.md if missing."""
    agents = project_root / "AGENTS.md"
    readme = project_root / "README.md"

    if not agents.exists():
        content = (
            "# Project Conventions\n\n"
            "This file defines the conventions for this project. "
            "Derived from the team construction projects as evidence — "
            "the shape is portable; no project content is shipped.\n\n"
            "## Skeletons\n\n"
            "Run `~/.omp/agent/skills/code-search/code-search.sh --skeletons` from "
            "the project root to generate `docs/skeletons/{project}_skeleton.md`. "
            "This is a capability, not a directory the seed creates — the file "
            "appears only when the skill runs.\n"
        )
        if dry_run:
            print(f"[dry-run] would create {agents}")
        else:
            agents.write_text(content)
            print(f"✓ Created {agents}")

    if not readme.exists():
        content = (
            "# Project Overview\n\n"
            "Essential documentation for this project.\n"
        )
        if dry_run:
            print(f"[dry-run] would create {readme}")
        else:
            readme.write_text(content)
            print(f"✓ Created {readme}")


def verify_seed(project_root: Path) -> bool:
    """Verify the seed is in place and the project is compliant."""
    seed_path = project_root / "seed.yaml"
    if not seed_path.exists():
        print("✗ seed.yaml missing")
        return False

    missing_files = [f for f in REQUIRED_FILES if not (project_root / f).exists()]
    missing_dirs = [d for d in REQUIRED_DIRS if not (project_root / d).is_dir()]

    if missing_files or missing_dirs:
        parts = []
        if missing_files:
            parts.append(f"files: {', '.join(missing_files)}")
        if missing_dirs:
            parts.append(f"dirs: {', '.join(missing_dirs)}")
        print(f"✗ Project missing required {' and '.join(parts)}")
        return False

    print("✓ Project is compliant with core conventions")
    return True


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Seed a new project with the team convention infrastructure."
    )
    parser.add_argument(
        "--project-root", required=True, help="Absolute path to the project root."
    )
    parser.add_argument(
        "--dry-run", action="store_true",
        help="Show what would be written without writing.",
    )
    parser.add_argument(
        "--verify-only", action="store_true", help="Only verify, do not write."
    )
    args = parser.parse_args(argv)

    project_root = Path(args.project_root).resolve()
    if not project_root.is_dir():
        print(f"✗ Project root does not exist: {project_root}", file=sys.stderr)
        return 2

    if args.verify_only:
        return 0 if verify_seed(project_root) else 1

    target = write_seed(project_root, SEED_CONTENT, dry_run=args.dry_run)
    print(f"{'[dry-run] ' if args.dry_run else ''}Seed written to {target}")

    scaffold_directories(project_root, dry_run=args.dry_run)
    scaffold_files(project_root, dry_run=args.dry_run)

    if not args.dry_run:
        ok = verify_seed(project_root)
        return 0 if ok else 1
    return 0


if __name__ == "__main__":
    sys.exit(main())